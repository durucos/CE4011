# PART 1: UNIT TESTS FOR CORE STRUCTURAL MECHANICS
# ==============================================================================
class TestCoreMechanics(unittest.TestCase):
    """
    Purpose: 
        Validates the fundamental finite element formulations including stiffness matrix 
        assembly, temperature gradient equivalent forces, and boundary conditions.
    """

    def setUp(self):
        """
        Purpose: 
            Initialize standard properties (C45 Concrete, 10m length span) for elemental testing.
        Assumptions: 
            2D planar coordinate system with 3 DOF per node (Ux, Uy, Rz).
        """
        self.mat = engine.Material(m_id=1, E=36e6, alpha_thermal=1e-5)
        self.sec = engine.Section(s_id=1, area=1.5, inertia=0.125, depth=1.5)
        self.n1 = engine.Node(n_id=1, x=0.0, y=0.0)
        self.n2 = engine.Node(n_id=2, x=10.0, y=0.0)
        self.member = engine.FrameMember(m_id=1, nodes=[self.n1, self.n2], material=self.mat, section=self.sec)

    def test_stiffness_matrix_symmetry_and_axial_value(self):
        """
        Purpose: 
            Verify Betti-Maxwell Reciprocal Theorem and correct axial stiffness formulation.
        """
        k = self.member.calculate_local_k()
        
        # 1. Symmetry Check (Betti-Maxwell Theorem)
        self.assertTrue(np.allclose(k, k.T), "ERROR: Local stiffness matrix is NOT symmetric!")
        
        # 2. Axial Stiffness Check (EA/L)
        expected_axial_stiffness = (self.mat.E * self.sec.area) / self.member.length
        self.assertAlmostEqual(k[0, 0], expected_axial_stiffness, places=2)
        self.assertAlmostEqual(k[3, 3], expected_axial_stiffness, places=2)
        self.assertAlmostEqual(k[0, 3], -expected_axial_stiffness, places=2)

    def test_thermal_load_fixed_end_forces(self):
        """
        Purpose: 
            Validate the internal equivalent forces generated by thermal expansion.
        """
        thermal_load = engine.MemberThermalLoad(member_id=1, tu=45.0, tb=10.0)
        fef = thermal_load.calc_equivalent_forces(self.member)
        
        T_avg = (45.0 + 10.0) / 2.0
        expected_fx = 1e-5 * 36e6 * 1.5 * T_avg
        
        # Check axial expansion forces (F = alpha * E * A * T_avg)
        self.assertAlmostEqual(fef[3], expected_fx, places=2)
        
        # Check thermal gradient bending moments (M = E * I * alpha * dT / h)
        expected_mz = (36e6 * 0.125 * 1e-5 * (10.0 - 45.0)) / 1.5
        self.assertAlmostEqual(fef[5], expected_mz, places=2)


